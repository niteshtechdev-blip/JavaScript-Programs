// Count Vowels
function countVowel(str){
    let count=0
    let arrStr=Array.from(str)
    for(ch of arrStr){
        if(ch=='a'||ch=='A'||ch=='e'||ch=='E'||ch=='i'||ch=='I'||ch=='o'||ch=='O'||ch=='u'||ch=='U'){
            count+=1
        }
    }
    console.log(count)
}
